    #region Helpers

    private static Dictionary<string, IOpenApiSchema> CollectProperties(IOpenApiSchema schema)
    {
        var result = new Dictionary<string, IOpenApiSchema>();

        // Properties from allOf subschemas (excluding $ref ones which become base types)
        if (schema.AllOf is { Count: > 0 })
        {
            foreach (IOpenApiSchema sub in schema.AllOf)
            {
                if (sub is OpenApiSchemaReference)
                {
                    continue; // Skip $ref entries, they become base types
                }

                if (sub.Properties != null)
                {
                    foreach ((string? name, IOpenApiSchema? prop) in sub.Properties)
                    {
                        result.TryAdd(name, prop);
                    }
                }
            }
        }

        // Direct properties
        if (schema.Properties != null)
        {
            foreach ((string? name, IOpenApiSchema? prop) in schema.Properties)
            {
                result.TryAdd(name, prop);
            }
        }

        return result;
    }

    /// <summary>
    /// Recursively collects all property names defined in a base type and its ancestors.
    /// Used to avoid re-declaring properties that would hide required base members (CS9031).
    /// </summary>
    private HashSet<string> CollectBasePropertyNames(IOpenApiSchema baseSchema)
    {
        var names = new HashSet<string>(StringComparer.Ordinal);

        // Resolve references through our schema dictionary
        IOpenApiSchema resolved = baseSchema;
        if (baseSchema is OpenApiSchemaReference schemaRef
            && schemaRef.Reference?.Id is not null
            && _allSchemas.TryGetValue(schemaRef.Reference.Id, out IOpenApiSchema? lookedUp))
        {
            resolved = lookedUp;
        }

        // Collect direct properties
        if (resolved.Properties != null)
        {
            foreach (string name in resolved.Properties.Keys)
            {
                names.Add(name);
            }
        }

        // Recurse into allOf to collect ancestor properties
        if (resolved.AllOf is { Count: > 0 })
        {
            foreach (IOpenApiSchema sub in resolved.AllOf)
            {
                if (sub.Properties != null)
                {
                    foreach (string name in sub.Properties.Keys)
                    {
                        names.Add(name);
                    }
                }

                // Follow $ref to ancestor types
                if (sub is OpenApiSchemaReference)
                {
                    foreach (string name in CollectBasePropertyNames(sub))
                    {
                        names.Add(name);
                    }
                }
            }
        }

        return names;
    }

    private static HashSet<string> CollectRequired(IOpenApiSchema schema)
    {
        var result = new HashSet<string>(StringComparer.Ordinal);

        if (schema.Required != null)
        {
            foreach (string r in schema.Required)
            {
                result.Add(r);
            }
        }

        // Collect required from allOf subschemas
        if (schema.AllOf is { Count: > 0 })
        {
            foreach (IOpenApiSchema sub in schema.AllOf)
            {
                if (sub.Required != null)
                {
                    foreach (string r in sub.Required)
                    {
                        result.Add(r);
                    }
                }
            }
        }

        return result;
    }

    private void EmitDocComment(string? description)
    {
        if (!_options.GenerateDocComments || string.IsNullOrWhiteSpace(description))
        {
            return;
        }

        string[] lines = description.Split(["\r\n", "\r", "\n"], StringSplitOptions.None);
        AppendLine("/// <summary>");
        foreach (string line in lines)
        {
            AppendLine($"/// {EscapeXmlDocComment(line)}");
        }
        AppendLine("/// </summary>");
    }

    private void EmitValidationAttributes(IOpenApiSchema schema)
    {
        if (!_options.EmitValidationAttributes)
        {
            return;
        }

        bool isString = TypeResolver.HasTypeFlag(schema, JsonSchemaType.String);
        bool isArray = TypeResolver.HasTypeFlag(schema, JsonSchemaType.Array);
        bool isNumber = TypeResolver.HasTypeFlag(schema, JsonSchemaType.Number) || TypeResolver.HasTypeFlag(schema, JsonSchemaType.Integer);

        if (isString)
        {
            int? minLength = schema.MinLength;
            int? maxLength = schema.MaxLength;

            if (minLength.HasValue || maxLength.HasValue)
            {
                if (minLength.HasValue && maxLength.HasValue)
                {
                    AppendLine($"[StringLength({maxLength.Value}, MinimumLength = {minLength.Value})]");
                }
                else if (maxLength.HasValue)
                {
                    AppendLine($"[StringLength({maxLength.Value})]");
                }
                else
                {
                    AppendLine($"[MinLength({minLength!.Value})]");
                }
            }
        }
        else if (isArray)
        {
            if (schema.MinItems.HasValue)
            {
                AppendLine($"[MinLength({schema.MinItems.Value})]");
            }

            if (schema.MaxItems.HasValue)
            {
                AppendLine($"[MaxLength({schema.MaxItems.Value})]");
            }
        }

        if (isString && !string.IsNullOrEmpty(schema.Pattern))
        {
            AppendLine($"[RegularExpression(\"{EscapeCSharpStringLiteral(schema.Pattern)}\")]");
        }

        if (isNumber && (!string.IsNullOrEmpty(schema.Minimum) || !string.IsNullOrEmpty(schema.Maximum)))
        {
            string min = !string.IsNullOrEmpty(schema.Minimum) ? FormatNumberLiteral(schema.Minimum) : "double.MinValue";
            string max = !string.IsNullOrEmpty(schema.Maximum) ? FormatNumberLiteral(schema.Maximum) : "double.MaxValue";
            AppendLine($"[Range({min}, {max})]");
        }
    }

    private static string FormatNumberLiteral(string value)
    {
        if (decimal.TryParse(value, NumberStyles.Any, CultureInfo.InvariantCulture, out decimal dec))
        {
            if (dec == decimal.Truncate(dec))
            {
                return dec.ToString("0", CultureInfo.InvariantCulture) + "d";
            }

            return dec.ToString(CultureInfo.InvariantCulture) + "d";
        }

        return value;
    }

    private void EmitObsoleteAttribute(IOpenApiSchema schema)
    {
        if (_options.EmitObsoleteAttribute && schema.Deprecated)
        {
            AppendLine("[Obsolete]");
        }
    }

    private static string EscapeXmlDocComment(string text)
    {
        return text
            .Replace("&", "&amp;", StringComparison.Ordinal)
            .Replace("<", "&lt;", StringComparison.Ordinal)
            .Replace(">", "&gt;", StringComparison.Ordinal);
    }

    private static string EscapeCSharpStringLiteral(string text)
    {
        var builder = new StringBuilder(text.Length);

        foreach (char ch in text)
        {
            switch (ch)
            {
                case '\\':
                    builder.Append("\\\\");
                    break;
                case '"':
                    builder.Append("\\\"");
                    break;
                case '\0':
                    builder.Append("\\0");
                    break;
                case '\a':
                    builder.Append("\\a");
                    break;
                case '\b':
                    builder.Append("\\b");
                    break;
                case '\f':
                    builder.Append("\\f");
                    break;
                case '\n':
                    builder.Append("\\n");
                    break;
                case '\r':
                    builder.Append("\\r");
                    break;
                case '\t':
                    builder.Append("\\t");
                    break;
                case '\v':
                    builder.Append("\\v");
                    break;
                default:
                    if (char.IsControl(ch) || ch is '\u2028' or '\u2029')
                    {
                        builder.Append("\\u");
                        builder.Append(((int) ch).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        builder.Append(ch);
                    }
                    break;
            }
        }

        return builder.ToString();
    }

    /// <summary>
    /// Emits a C# block: the prefix line(s), an opening brace, the body
    /// (at an increased indent level), and a closing brace. Supports
    /// multi-line prefixes (e.g. a declaration followed by a where clause)
    /// by splitting on newlines.
    /// </summary>
    private void AppendBlock(string prefix, Action act)
    {
        foreach (string line in prefix.Split('\n'))
        {
            AppendLine(line.TrimEnd('\r'));
        }

        AppendLine("{");
        _indent++;
        act();
        _indent--;
        AppendLine("}");
    }

    private void AppendLine(string? text = null)
    {
        if (text == null)
        {
            _sb.AppendLine();
        }
        else
        {
            _sb.Append(new string(' ', _indent * 4));
            _sb.AppendLine(text);
        }
    }

    private void Append(string text)
    {
        _sb.Append(new string(' ', _indent * 4));
        _sb.Append(text);
    }

    private void AppendLineRaw(string text)
    {
        _sb.AppendLine(text);
    }

