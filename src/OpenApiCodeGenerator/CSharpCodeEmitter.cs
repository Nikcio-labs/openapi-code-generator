    #region Type Alias Emission

    private void EmitTypeAlias(string schemaName, IOpenApiSchema schema, string? typeNameOverride = null)
    {
        string typeName = typeNameOverride ?? NameHelper.ToTypeName(schemaName, _options.ModelPrefix);
        string resolvedType = _typeResolver.ResolveUnderlyingType(schema);

        EmitDocComment(schema.Description);

        // C# doesn't have direct type aliases at the top level.
        // We emit a global using alias or a wrapper record.
        // For simplicity and usability, emit a readonly record struct wrapping the value.
        AppendLine($"/// <summary>");
        AppendLine($"/// Type alias for {resolvedType}.");
        AppendLine($"/// </summary>");

        EmitObsoleteAttribute(schema);

        if (!_options.InlinePrimitiveTypeAliases)
        {
            string converterType = _typeResolver.IsBinaryStreamPropertyType(schema)
                ? $"OpenApiGeneratedBinaryStreamTypeAliasJsonConverter<{typeName}>"
                : $"OpenApiGeneratedTypeAliasJsonConverter<{typeName}, {resolvedType}>";

            AppendLine($"[JsonConverter(typeof({converterType}))]");
        }

        AppendBlock($"public readonly partial record struct {typeName}({resolvedType} Value) : IOpenApiGeneratedTypeAlias<{typeName}, {resolvedType}>", () =>
        {
            AppendLine($"public static {typeName} Create({resolvedType} value) => new(value);");
        });
        AppendLine();
    }

